/**
 * Writes the migration that puts the steel grades' "i" info (scripts/data/steel-grades.mjs) into the database:
 *   - app.trade_template('steel'): what a newly registered steel business starts with
 *   - grades already in the app get the fuller info; any text the shop changed itself is kept.
 *
 *   node scripts/gen-steel-template.mjs 20260929090000_grade_info
 * Migrations are append-only: for later text changes, run it again with a NEW file name.
 */
import fs from 'node:fs';
import path from 'node:path';
import { GRADES } from './data/steel-grades.mjs';

const name = process.argv[2];
if (!/^\d{14}_[a-z0-9_]+$/.test(name || '')) { console.error('usage: node scripts/gen-steel-template.mjs <14-digit-version>_<name>'); process.exit(1); }
const json = JSON.stringify(GRADES);
if (json.includes('$tpl$')) throw new Error('text contains $tpl$');
const sql = `-- Steel grades: fuller "i" information (what it is, uses, what it's made of, strength, how to work it,
-- alternatives, a line for the customer) in English, Hindi and Hinglish. Generated by
-- scripts/gen-steel-template.mjs from scripts/data/steel-grades.mjs — edit that file, not this one.
-- Densities, rates and codes are unchanged.

-- the old starting text, to tell apart grades whose notes the shop has edited
create temporary table old_steel_info on commit drop as
  select e ->> 'code' as code, e -> 'info' as info from jsonb_array_elements(app.trade_template('steel')) e;

create or replace function app.trade_template(p_trade text) returns jsonb
language sql immutable set search_path = '' as $$
  select case p_trade
    when 'steel' then $tpl$${json}$tpl$::jsonb
    else '[]'::jsonb end
$$;

-- grades already in the app: take the new info; where the shop changed a note, keep the shop's words
with t as (select e ->> 'code' as code, e -> 'info' as info from jsonb_array_elements(app.trade_template('steel')) e)
update public.materials m
   set info = case
     when m.info is null or m.info = o.info then t.info
     else t.info || jsonb_strip_nulls(jsonb_build_object(
       'what',  case when m.info -> 'what'  is distinct from o.info -> 'what'  then m.info -> 'what'  end,
       'good',  case when m.info -> 'good'  is distinct from o.info -> 'good'  then m.info -> 'good'  end,
       'watch', case when m.info -> 'watch' is distinct from o.info -> 'watch' then m.info -> 'watch' end,
       'alts',  case when m.info -> 'alts'  is distinct from o.info -> 'alts'  then m.info -> 'alts'  end))
   end
  from t left join old_steel_info o on o.code = t.code
 where m.code = t.code and coalesce((m.info ->> 'v')::int, 1) < 2;
`;
const file = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'supabase', 'migrations', `${name}.sql`);
fs.writeFileSync(file, sql);
console.log(`✓ wrote ${path.relative(process.cwd(), file)} (${GRADES.length} grades, ${Math.round(sql.length / 1024)} KB)`);
